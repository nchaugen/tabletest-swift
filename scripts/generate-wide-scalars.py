#!/usr/bin/env python3
"""Writes Sources/TableTestFormat/WideScalars.swift: the ranges of the Unicode scalars that draw
two columns on their own, East Asian Width W (wide) or F (fullwidth), or Emoji_Presentation.

The JVM formatter generates the same table from the same data
(tabletest-formatter/scripts/generate-wide-code-points.py), so both formatters measure alike
whatever the Unicode version of their runtime. East Asian Width comes from the Unicode data of
the Python that runs this script; Emoji_Presentation from emoji-data.txt of the same version.

    curl -sO https://www.unicode.org/Public/<version>/ucd/emoji/emoji-data.txt
    python3 scripts/generate-wide-scalars.py emoji-data.txt
"""
import os
import re
import sys
import unicodedata

wide = {cp for cp in range(sys.maxunicode + 1) if unicodedata.east_asian_width(chr(cp)) in ("W", "F")}

emoji_version = None
for line in open(sys.argv[1], encoding="utf-8"):
    version = re.match(r"# Version: (\S+)", line)
    if version:
        emoji_version = version.group(1)
    fields = line.split("#")[0].split(";")
    if len(fields) == 2 and fields[1].strip() == "Emoji_Presentation":
        first, _, last = fields[0].strip().partition("..")
        wide.update(range(int(first, 16), int(last or first, 16) + 1))

if not unicodedata.unidata_version.startswith(emoji_version or "?"):
    sys.exit(f"Unicode {unicodedata.unidata_version} in Python, but emoji data {emoji_version}")

ranges = []
for cp in sorted(wide):
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

rows = "\n".join(
    "        " + " ".join(f"(0x{a:04X}, 0x{b:04X})," for a, b in ranges[start:start + 4])
    for start in range(0, len(ranges), 4)
)
source = f'''// Generated by scripts/generate-wide-scalars.py from Unicode {unicodedata.unidata_version}. Do not edit.

/// The Unicode scalars that draw two columns on their own: East Asian Width W (wide) or F
/// (fullwidth), or Emoji_Presentation.
enum WideScalars {{
    /// Whether the scalar draws two columns on its own.
    static func contains(_ scalar: Unicode.Scalar) -> Bool {{
        var low = 0
        var high = ranges.count - 1
        while low <= high {{
            let middle = (low + high) / 2
            let range = ranges[middle]
            if scalar.value < range.first {{
                high = middle - 1
            }} else if scalar.value > range.last {{
                low = middle + 1
            }} else {{
                return true
            }}
        }}
        return false
    }}

    /// Sorted, non-overlapping ranges, first and last included: {len(ranges)} ranges.
    private static let ranges: [(first: UInt32, last: UInt32)] = [
{rows}
    ]
}}
'''
target = os.path.join(os.path.dirname(__file__), "..", "Sources", "TableTestFormat", "WideScalars.swift")
with open(target, "w", encoding="utf-8") as file:
    file.write(source)
print(f"Wrote {len(ranges)} ranges from Unicode {unicodedata.unidata_version}")
